const defaultRuntime = Object.freeze({
  stagedFileList: false,
  allTracked: false,
  telemetryPrefix: false,
});

const defaultGate = {
  dependsOn: Object.freeze([]),
  parallelizable: false,
  profiles: Object.freeze(["fast", "full", "strict"]),
  telemetryPhase: "quality_gate",
  isTestSuite: false,
  postGate: null,
  runner: "command",
  triggerField: null,
  failureTarget: null,
  suppressFirstFailure: false,
  runtime: defaultRuntime,
};

const makeGate = (definition) => Object.freeze({
  ...defaultGate,
  ...definition,
  dependsOn: Object.freeze(definition.dependsOn || defaultGate.dependsOn),
});

const makeQualityGate = ({
  id,
  command,
  args,
  triggerField = null,
  dependsOn = [],
  parallelizable = false,
  profiles = ["fast", "full", "strict"],
  telemetryPhase = "quality_gate",
  runtime = defaultRuntime,
  suppressFirstFailure = false,
  qualityCategory,
}) => {
  return makeGate({
    id,
    phase: "quality",
    command,
    args,
    triggerField,
    telemetryPhase,
    runtime,
    suppressFirstFailure,
    qualityCategory,
    dependsOn,
    parallelizable,
    profiles: Object.freeze(profiles),
  });
};

const makePreflightGate = ({
  id,
  command,
  args,
  triggerField = null,
  profiles = ["fast", "full", "strict"],
  runner = "command",
  telemetryPhase,
  failureTarget = null,
  runtime = defaultRuntime,
  dependsOn = [],
}) => {
  return makeGate({
    id,
    phase: "preflight",
    command,
    args,
    triggerField,
    profiles: Object.freeze(profiles),
    runner,
    telemetryPhase,
    failureTarget,
    runtime,
    dependsOn,
  });
};

const makeTestSuiteGate = ({
  id,
  name,
  command,
  args,
  commandContext,
  profiles = ["fast", "full", "strict"],
  dependsOn = [],
}) => {
  return makeGate({
    id,
    phase: "test_suite",
    suiteName: name,
    command,
    args,
    commandContext,
    isTestSuite: true,
    telemetryPhase: "test_suite",
    profiles: Object.freeze(profiles),
    dependsOn,
  });
};

